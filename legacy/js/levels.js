/* Validate at load: rows must be W wide, one H, at least one X. */
for (const lv of LEVELS) {
  if (lv.map.length !== 27) console.warn(`[levels] ${lv.id}: ${lv.map.length} rows (want 27)`);
  lv.map.forEach((row, y) => {
    if (row.length !== 80) console.warn(`[levels] ${lv.id}: row ${y} len ${row.length} (want 80)`);
    if (row.length > 80) lv.map[y] = row.slice(0, 80);
    else if (row.length < 80) lv.map[y] = row + ".".repeat(80 - row.length);
  });
}
