/* Scripted solution for the HAZARD LAB. Run: node tools/solve-lab.js [--write] */
"use strict";
const { load, ROOT } = require("./load.js");
const { runPlan, report } = require("./plan.js");
const OL = load();
const lv = OL.getLevel("hazard-lab");
const W = (l) => l.state === "walk";
const PLANS = {
  "tunnel-and-bridge": [
    { who: 1, skill: "digger", when: (l) => W(l) && l.x >= 110, note: "dig before the press" },
    { who: 1, skill: "basher", when: (l) => l.state === "dig" && l.y >= 118, note: "tunnel under the OOM killer" },
    { who: 2, skill: "blocker", when: (l) => W(l) && l.x >= 380 && l.y > 140, note: "hold the crowd before the lava" },
    { who: 1, skill: "builder", when: (l) => W(l) && l.x >= 414 && l.y > 140 && l.dir > 0, note: "own bridge, part 1" },
    { who: 1, skill: "builder", when: (l) => W(l) && l.x >= 440 && l.dir > 0, note: "own bridge, part 2" },
    { who: 2, skill: "builder", when: (l, s) => s.lem(1).x > 520, note: "release onto the stairs" },
  ],
};
const out = {};
for (const [name, plan] of Object.entries(PLANS)) {
  const r = runPlan(OL, lv, plan);
  report(name, r);
  out[name] = { saved: r.sim.saved, used: r.sim.used, actions: r.sim.actions, notes: plan.map((s) => s.note) };
  if (r.sim.status !== "won" && process.argv.includes("--write")) { console.error("not writing: " + name + " lost"); process.exit(1); }
}
report("do nothing", runPlan(OL, lv, []));
if (process.argv.includes("--write")) {
  require("fs").writeFileSync(require("path").join(ROOT, "levels/solutions-lab.js"),
    "/* Recorded solutions for the HAZARD LAB. Generated by tools/solve-lab.js --write. */\n" +
    "OL.registerSolutions(\"hazard-lab\", " + JSON.stringify(out, null, 1) + ");\n");
  console.log("\nwrote levels/solutions-lab.js");
}
