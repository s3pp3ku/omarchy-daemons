/* Scripted solutions + probes for LVL 03 DEPENDENCIES.
   Run: node tools/solve-03.js [--write] [--random N]
   Lemmings alternate hatches: odd ids are group A (deck), even ids group B (/var/cache). */
"use strict";
const { load, ROOT } = require("./load.js");
const { runPlan, report } = require("./plan.js");
const OL = load();
const lv = OL.getLevel("dependencies");
const W = (l) => l.state === "walk";
const A = (l) => l.id % 2 === 1;
const corr = (l) => l.y > 260 && l.x > 322;

function dais(x0) {
  let id = 0;
  return [
    { skill: "builder", when: (l) => { if (A(l) && W(l) && corr(l) && l.dir > 0 && l.x >= (x0 || 940)) { id = l.id; return true; } return false; }, note: "A: first flight of steps toward the dais" },
    { skill: "builder", when: (l) => l.id === id && W(l) && l.dir > 0, note: "A: second flight, onto the dais" },
  ];
}
const door = { skill: "basher", when: (l) => A(l) && W(l) && l.y > 260 && l.dir < 0 && l.x <= 326, note: "A: bash the one-way door open from outside" };

const PLANS = {
  "B-bridges-first": [
    { who: 2, skill: "builder", when: (l) => W(l) && l.y > 260 && l.x >= 234, note: "B: the first B lemming bridges the pit at once" },
    { who: 4, skill: "blocker", when: (l) => W(l) && l.y > 260 && l.x >= 200, note: "B: the next one holds the rest of B" },
    ...dais(),
    door,
    { who: 4, skill: "basher", when: (l, s) => s.used.basher === 1, note: "B: release (nothing to bash, so he walks)" },
  ],
  "hold-at-the-lip": [
    { who: 2, skill: "blocker", when: (l) => W(l) && l.y > 260 && l.x >= 232, note: "B: hold everyone right at the pit's edge" },
    ...dais(),
    door,
    { who: 2, skill: "builder", when: (l, s) => s.used.basher === 1, note: "B: the blocker becomes the bridge — release and crossing in one" },
  ],
};

const LAZY = {
  "no B containment (bridge only)": [{ who: 2, skill: "builder", when: (l) => W(l) && l.y > 260 && l.x >= 234 }, ...dais(), door],
  "release B before the door opens": [
    { who: 2, skill: "blocker", when: (l) => W(l) && l.y > 260 && l.x >= 232 }, ...dais(),
    { who: 2, skill: "builder", when: (l, s) => s.tick > 600 }, door],
  "A digs into /var/cache from the deck": [
    { who: 2, skill: "blocker", when: (l) => W(l) && l.y > 260 && l.x >= 232 },
    { who: 1, skill: "digger", when: (l) => W(l) && l.y < 110 && l.x >= 150 }, ...dais()],
  "B tunnels under the door": [
    { who: 2, skill: "blocker", when: (l) => W(l) && l.y > 260 && l.x >= 200 },
    { who: 4, skill: "builder", when: (l) => W(l) && l.y > 260 && l.x >= 234 },
    { who: 4, skill: "digger", when: (l) => W(l) && l.y > 260 && l.x >= 292 },
    { who: 4, skill: "basher", when: (l) => l.state === "dig" && l.y >= 284 }, ...dais()],
  "only A gets home": [...dais()],
};

const out = {};
for (const [name, plan] of Object.entries(PLANS)) {
  const r = runPlan(OL, lv, plan);
  report(name, r);
  out[name] = { saved: r.sim.saved, used: r.sim.used, actions: r.sim.actions, notes: plan.map((s) => s.note) };
  if (r.sim.status !== "won" && process.argv.includes("--write")) { console.error("not writing: " + name); process.exit(1); }
}
console.log("\n--- lazy / wrong strategies ---");
for (const [name, plan] of Object.entries(LAZY)) { const r = runPlan(OL, lv, plan); console.log(`${r.sim.status === "won" ? "WON " : "lost"}  ${r.sim.saved}/${r.sim.total}  ${name}`); }

if (process.argv.includes("--random")) {
  const N = +process.argv[process.argv.indexOf("--random") + 1] || 5000;
  const skills = Object.keys(lv.skills);
  let rng = 4242; const rnd = () => ((rng = (rng * 1103515245 + 12345) & 0x7fffffff) / 0x7fffffff);
  let wins = 0; const t0 = Date.now(), K0 = +(process.env.KMIN || 1), K1 = +(process.env.KMAX || 4);
  for (let i = 0; i < N; i++) {
    const k = K0 + Math.floor(rnd() * (K1 - K0 + 1)), acts = [];
    for (let j = 0; j < k; j++) acts.push({ t: Math.floor(rnd() * 2200), a: "assign", id: 1 + Math.floor(rnd() * 10), skill: skills[Math.floor(rnd() * skills.length)] });
    if (OL.runReplay(lv, acts).status === "won") { wins++; console.log("WIN", JSON.stringify(acts)); }
  }
  console.log(`random search: ${N} plans of ${K0}-${K1} actions, ${wins} wins (${((Date.now() - t0) / 1000).toFixed(0)}s)`);
}

if (process.argv.includes("--write")) {
  require("fs").writeFileSync(require("path").join(ROOT, "levels/solutions-03.js"),
    "/* Recorded solutions for LVL 03. Generated by tools/solve-03.js --write. */\n" +
    "OL.registerSolutions(\"dependencies\", " + JSON.stringify(out, null, 1) + ");\n");
  console.log("\nwrote levels/solutions-03.js");
}
