/* Generates levels/12-segfault.js */
"use strict";
const k = require("./lib.js");
const { r } = k;
const W = 440;
const z = k.zigzag({ floors: 6, W });
const F = z.F, x0 = z.x0, x1 = z.x1;
const terrain = [...z.ops];

/* ice floors (not over the drops) */
for (let i = 0; i < 6; i++) {
  if (i % 2 === 0) terrain.push(r("ice", x0, F[i], x1 - 80 - x0, 8));
  else terrain.push(r("ice", 100, F[i], x1 - 100, 8));
}
/* tolls: presses on floors 0, 3, 5; pits on 1 and 4; a wall on 2 */
terrain.push(r("rock", 100, 40, 16, F[0] - 40));                      // bay wall on floor 1
terrain.push(...k.pit(300, F[1], 36, "lava", 22));
terrain.push(r("rock", 200, F[2] - 64, 16, 64));
terrain.push(...k.pit(120, F[4], 36, "water", 22));
terrain.push(r("tech", 40, F[5], 60, 3));
terrain.push(k.poly("rock", [[20, 40], [420, 40], [420, 60], [300, 60], [300, 50], [160, 50], [160, 66], [20, 66]]));

