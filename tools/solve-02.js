const results = {};
for (const [name, plan] of Object.entries(PLANS)) {
  const r = runPlan(OL, lv, plan, { trace: process.argv.includes("--trace") ? 100 : 0 });
  report(name, r);
  results[name] = r;
}
module.exports = { PLANS };
if (process.argv.includes("--write")) {
  const fs = require("fs");
  const out = {};
  for (const [name, r] of Object.entries(results)) {
    if (r.sim.status !== "won") { console.error("not writing: " + name + " did not win"); process.exit(1); }
    out[name] = { saved: r.sim.saved, used: r.sim.used, actions: r.sim.actions, notes: PLANS[name].map((s) => s.note) };
  }
  const txt = "/* Recorded solutions (replay action lists), verified by tools/verify.js.\n   Generated by tools/solve-02.js --write. Do not edit by hand. */\n" +
    "OL.registerSolutions(\"network-nodes\", " + JSON.stringify(out, null, 1) + ");\n";
  fs.writeFileSync(require("path").join(ROOT, "levels/solutions-02.js"), txt);
  console.log("\nwrote levels/solutions-02.js");
}
