/* Run scripted solutions for a level and (optionally) record them.
     node tools/solve.js 01 [--write] [--only NAME]
   tools/solve-NN.js exports { LEVEL: "<level id>", FILE: "levels/solutions-NN.js", PLANS }. */
"use strict";
const { load, ROOT } = require("./load.js");
const { runPlan, report } = require("./plan.js");
const OL = load();
const nn = process.argv[2];
const { LEVEL, FILE, PLANS } = require("./solve-" + nn + ".js");
const lv = OL.getLevel(LEVEL);
const oi = process.argv.indexOf("--only");
const only = oi > 0 ? process.argv[oi + 1] : null;
const results = {};
for (const [name, plan] of Object.entries(PLANS)) {
  if (only && name !== only) continue;
  const r = runPlan(OL, lv, plan);
  report(name, r);
  results[name] = r;
}
if (process.argv.includes("--write")) {
  const fs = require("fs");
  const out = {};
  for (const [name, r] of Object.entries(results)) {
    if (r.sim.status !== "won") { console.error("not writing: " + name + " did not win"); process.exit(1); }
    out[name] = { saved: r.sim.saved, used: r.sim.used, actions: r.sim.actions, notes: PLANS[name].map((s) => s.note) };
  }
  const txt = `/* Recorded solutions (replay action lists), verified by tools/verify.js.\n   Generated by tools/solve.js ${nn} --write. Do not edit by hand. */\n` +
    `OL.registerSolutions(${JSON.stringify(LEVEL)}, ${JSON.stringify(out, null, 1)});\n`;
  fs.writeFileSync(require("path").join(ROOT, FILE), txt);
  console.log("\nwrote " + FILE);
}
